#define BN_DIGIT_GAP 2   /* অঙ্কের মাঝের ফাঁক (পিক্সেল) */

/* একটি সংখ্যাকে বাংলা অঙ্কের সূচকের তালিকায় ভাঙা হয় */
inline uint8_t bnSplitNumber(float value, uint8_t decimals, uint8_t *idx, uint8_t maxLen) {
  uint8_t n = 0;
  bool neg = value < 0;
  if (neg) value = -value;

  uint32_t mult = 1;
  for (uint8_t i = 0; i < decimals; i++) mult *= 10;
  uint32_t scaled = (uint32_t)(value * mult + 0.5f);

  char tmp[16];
  uint8_t t = 0;
  if (scaled == 0) tmp[t++] = 0;
  while (scaled > 0 && t < 15) { tmp[t++] = scaled % 10; scaled /= 10; }
  while (t <= decimals) tmp[t++] = 0;

  if (neg && n < maxLen) idx[n++] = 11;
  for (int8_t i = t - 1; i >= 0; i--) {
    if (decimals > 0 && i == decimals - 1 && n < maxLen) idx[n++] = 10;
    if (n < maxLen) idx[n++] = tmp[i];
  }
  return n;
}

/* সংখ্যার মোট প্রস্থ (মাঝ বরাবর বসানোর জন্য) */
inline uint16_t bnNumberWidth(float value, uint8_t decimals, bool big) {
  uint8_t idx[16];
  uint8_t n = bnSplitNumber(value, decimals, idx, 16);
  const BnGlyph *set = big ? BN_BIG : BN_SMALL;
  uint16_t w = 0;
  for (uint8_t i = 0; i < n; i++) w += set[idx[i]].w + BN_DIGIT_GAP;
  return w > 0 ? w - BN_DIGIT_GAP : 0;
}

/* বাংলা অঙ্কে সংখ্যা আঁকা — (x, y) উপরের-বাঁ কোণ */
template <class T>
inline void bnDrawNumber(T &u8g2, int x, int y, float value, uint8_t decimals, bool big) {
  uint8_t idx[16];
  uint8_t n = bnSplitNumber(value, decimals, idx, 16);
  const BnGlyph *set = big ? BN_BIG : BN_SMALL;
  for (uint8_t i = 0; i < n; i++) {
    u8g2.drawXBMP(x, y, set[idx[i]].w, set[idx[i]].h, set[idx[i]].bmp);
    x += set[idx[i]].w + BN_DIGIT_GAP;
  }
}

template <class T>
inline void bnDrawNumberCentered(T &u8g2, int y, float value, uint8_t decimals, bool big, int screenW = 128) {
  bnDrawNumber(u8g2, (screenW - bnNumberWidth(value, decimals, big)) / 2, y, value, decimals, big);
}

